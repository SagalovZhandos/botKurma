def quote_of_day(day: date, quotes: tuple[Quote, ...] = QUOTES) -> Quote:
    """Идёт по списку шагом, взаимно простым с его длиной: все цитаты по кругу, соседние дни — разные по стилю."""
    step = next(s for s in range(7, 7 + len(quotes) + 1) if math.gcd(s, len(quotes)) == 1)
    return quotes[(day.toordinal() * step) % len(quotes)]


def format_quote(q: Quote) -> str:
    lines = [f"«{html.escape(q.text)}»"]
    if q.original:
        lines.append(f"<i>{html.escape(q.original)}</i>")
    lines.append(f"— {html.escape(q.author)}")
    return "\n".join(lines)
